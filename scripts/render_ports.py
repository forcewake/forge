"""Render the engine port reference from its declaration docstrings and signatures."""

import argparse
import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src/forge/ports.py"
DESTINATION = ROOT / "docs/reference/ports.md"


def render(source: Path = SOURCE) -> str:
    parts = ["# Engine ports", "Generated by `scripts/render_ports.py` from `src/forge/ports.py`."]
    module = ast.parse(source.read_text(encoding="utf-8"))
    parts.append(ast.get_docstring(module) or "")
    for node in module.body:
        if not isinstance(node, ast.ClassDef):
            continue
        parts.extend((f"## {node.name}", ast.get_docstring(node) or ""))
        signatures = []
        for method in node.body:
            if isinstance(method, (ast.FunctionDef, ast.AsyncFunctionDef)):
                signatures.append(ast.unparse(method))
        parts.append("```python\n" + "\n\n".join(signatures) + "\n```")
    return "\n\n".join(parts) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="refuse a stale generated reference")
    args = parser.parse_args()
    generated = render()
    if args.check:
        if DESTINATION.read_text(encoding="utf-8") != generated:
            raise SystemExit("engine port reference is stale; run scripts/render_ports.py")
    else:
        DESTINATION.write_text(generated, encoding="utf-8")


if __name__ == "__main__":
    main()
